import { afterEach, describe, expect, it, vi } from 'vitest'
import fs from 'fs'
import path from 'path'
import { createRecordingService } from './index'
import type { RecordingService } from '../../shared/recording'
import { createSegments, ffmpeg, fakeCommand, fakeLiveCommand, makeDeps, tempRoot, waitFor } from './test-support'
import { fakeObs } from './obs-test-support'

const cleanup: Array<() => Promise<void> | void> = []
afterEach(async () => { for (const fn of cleanup.splice(0).reverse()) await fn(); vi.restoreAllMocks() })
async function rig(server: Awaited<ReturnType<typeof fakeObs>> | null, fallback = true) {
  const root = tempRoot(); cleanup.push(() => fs.rmSync(root, { recursive: true, force: true }))
  const trace = path.join(root, 'trace.jsonl')
  const deps = makeDeps(root)
  deps.getSettings = () => ({ ...makeDeps(root).getSettings(), autoRecord: false, backend: 'obs', obsPort: server?.port ?? 1,
    obsFallbackBuiltin: fallback })
  deps.recorderCommand = fakeCommand('normal', { FAKE_RECORDER_TRACE: trace })
  deps.liveEngineCommand = fakeLiveCommand()
  deps.notify = vi.fn()
  deps.obsReconnectBaseMs = 10
  const service: RecordingService = createRecordingService(deps)
  cleanup.push(() => service.stop())
  service.start()
  await waitFor(() => fs.existsSync(root))
  return { service, deps, trace, root }
}
describe('OBS 錄影生命週期', () => {
  it.skipIf(!ffmpeg)('停止後原檔加入媒體庫，live 事件按 obs.json 位移', async () => {
    const root = tempRoot(); cleanup.push(() => fs.rmSync(root, { recursive: true, force: true }))
    createSegments(root)
    const outputPath = path.join(root, 'source.mp4')
    const bytes = fs.readFileSync(outputPath)
    const server = await fakeObs({ outputPath }); cleanup.push(server.close)
    const r = await rig(server)
    r.deps.addToLibrary = vi.fn()
    r.deps.liveCachePath = (file) => file + '.apexhl.json'
    r.deps.probeVideo = async () => ({ duration: 4, width: 160, height: 90, codec: 'mpeg4' })
    await r.service.startManual()
    await waitFor(() => r.service.status().kills > 0)
    const dir = path.join(r.root, 'videos', '.sessions', r.service.status().sessionId!)
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'obs.json'), 'utf8'))
    await r.service.stopManual()
    expect(r.deps.addToLibrary).toHaveBeenCalledWith([outputPath])
    const cache = JSON.parse(fs.readFileSync(outputPath + '.apexhl.json', 'utf8'))
    expect(cache.events[0].t).toBeCloseTo(1 + (meta.captureStartedAt - meta.recordStartedAt) / 1000)
    expect(cache.video).toMatchObject({ duration: 4, width: 160, height: 90, codec: 'mpeg4' })
    expect(fs.readFileSync(outputPath)).toEqual(bytes)
  })

  it('開始與停止由 OBS 負責；apexrec 只擷取且可接收即時事件', async () => {
    const server = await fakeObs({ password: '測試密碼' }); cleanup.push(server.close)
    const r = await rig(server)
    r.deps.getObsPassword = () => '測試密碼'
    expect(await r.service.testObs!()).toMatchObject({ ok: true, obsVersion: '31.0.0' })
    expect(server.calls).not.toContain('StartRecord')
    expect(await r.service.startManual()).toBe(true)
    expect(r.service.status()).toMatchObject({ phase: 'recording', backend: 'obs' })
    const start = fs.readFileSync(r.trace, 'utf8').trim().split('\n').map((s) => JSON.parse(s)).find((v) => v.cmd === 'start')
    expect(start).toMatchObject({ encode: null, audio: null, capture: 'dda' })
    expect(server.calls.filter((c) => c === 'StartRecord')).toHaveLength(1)
    await r.service.stopManual()
    expect(server.calls.filter((c) => c === 'StopRecord')).toHaveLength(1)
  })
  it('沿用既有錄影不開始、不停止；停止偵測後仍等候 OBS 停止事件', async () => {
    const server = await fakeObs({ recording: true, duration: 90000 }); cleanup.push(server.close)
    const r = await rig(server)
    await r.service.startManual()
    const dir = path.join(r.root, 'videos', '.sessions', r.service.status().sessionId!)
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'obs.json'), 'utf8'))
    expect(meta.adopted).toBe(true)
    expect(meta.captureStartedAt - meta.recordStartedAt).toBeGreaterThanOrEqual(90000)
    await r.service.stopManual()
    expect(fs.existsSync(dir)).toBe(true)
    expect(server.calls).not.toContain('StartRecord')
    expect(server.calls).not.toContain('StopRecord')
    server.event('OBS_WEBSOCKET_OUTPUT_STOPPED')
    await waitFor(() => !fs.existsSync(dir))
  })
  it.skipIf(!ffmpeg)('沿用錄影在 App 執行期間停止後加入媒體庫', async () => {
    const root = tempRoot(); cleanup.push(() => fs.rmSync(root, { recursive: true, force: true }))
    createSegments(root)
    const outputPath = path.join(root, 'source.mp4')
    const server = await fakeObs({ recording: true, duration: 0, outputPath }); cleanup.push(server.close)
    const r = await rig(server)
    r.deps.addToLibrary = vi.fn()
    r.deps.probeVideo = async () => ({ duration: 4 })
    await r.service.startManual()
    server.event('OBS_WEBSOCKET_OUTPUT_STOPPED')
    await waitFor(() => r.service.status().phase === 'idle')
    expect(r.deps.addToLibrary).toHaveBeenCalledWith([outputPath])
    expect(server.calls).not.toContain('StartRecord')
    expect(server.calls).not.toContain('StopRecord')
  })
  it.skipIf(!ffmpeg)('擷取沒啟動就失敗時，不把沿用的 OBS 錄影加入媒體庫', async () => {
    const root = tempRoot(); cleanup.push(() => fs.rmSync(root, { recursive: true, force: true }))
    createSegments(root)
    const outputPath = path.join(root, 'source.mp4')
    const server = await fakeObs({ recording: true, duration: 5000, outputPath }); cleanup.push(server.close)
    const r = await rig(server)
    r.deps.recorderCommand = fakeCommand('no-hw')
    r.deps.addToLibrary = vi.fn()
    r.deps.probeVideo = async () => ({ duration: 4 })
    expect(await r.service.startManual()).toBe(false)
    server.event('OBS_WEBSOCKET_OUTPUT_STOPPED')
    await new Promise((resolve) => setTimeout(resolve, 1500))
    expect(r.deps.addToLibrary).not.toHaveBeenCalled()
    expect(server.calls).not.toContain('StopRecord')
    const sessions = path.join(r.root, 'videos', '.sessions')
    expect(fs.existsSync(sessions) ? fs.readdirSync(sessions) : []).toEqual([])
  })
  it('剛停止自己的錄影後 OBS 仍回報錄影中，等它停下再開始新錄影而不是沿用', async () => {
    const server = await fakeObs({ outputPath: 'C:/obs/a.mkv' }); cleanup.push(server.close)
    const r = await rig(server)
    r.deps.obsStopGraceMs = 2000
    await r.service.startManual()
    await r.service.stopManual()
    // 模擬 OBS 停止中：狀態仍是錄影中，稍後才真正停止。
    server.setRecording(true)
    setTimeout(() => server.setRecording(false), 150)
    await r.service.startManual()
    const dir = path.join(r.root, 'videos', '.sessions', r.service.status().sessionId!)
    expect(JSON.parse(fs.readFileSync(path.join(dir, 'obs.json'), 'utf8')).adopted).toBe(false)
    expect(server.calls.filter((c) => c === 'StartRecord')).toHaveLength(2)
  })
  it('自動偵測 Apex 也會啟動 OBS 並使用純擷取模式', async () => {
    const server = await fakeObs(); cleanup.push(server.close)
    const r = await rig(server)
    const settings = r.deps.getSettings()
    r.deps.getSettings = () => ({ ...settings, autoRecord: true })
    await waitFor(() => r.service.status().phase === 'recording')
    expect(r.service.status().backend).toBe('obs')
    expect(server.calls).toContain('StartRecord')
    const requests = fs.readFileSync(r.trace, 'utf8').trim().split('\n').map((s) => JSON.parse(s))
    expect(requests.find((r) => r.cmd === 'start').encode).toBeNull()
  })
  it.each([true, false])('OBS 無法連線：回退設定 %s', async (fallback) => {
    const r = await rig(null, fallback)
    expect(await r.service.startManual()).toBe(true)
    const start = fs.readFileSync(r.trace, 'utf8').trim().split('\n').map((s) => JSON.parse(s)).find((v) => v.cmd === 'start')
    expect(start.encode === null).toBe(!fallback)
    expect(r.service.status().backend).toBe(fallback ? 'builtin' : 'obs')
    expect(r.deps.notify).toHaveBeenCalled()
    await r.service.stopManual()
  })
  it('斷線時擷取持續，退避重連不重複開始錄影', async () => {
    const server = await fakeObs(); cleanup.push(server.close)
    const r = await rig(server)
    await r.service.startManual()
    server.disconnect()
    await waitFor(() => server.calls.filter((c) => c === 'GetRecordStatus').length >= 2)
    expect(r.service.status().phase).toBe('recording')
    expect(server.calls.filter((c) => c === 'StartRecord')).toHaveLength(1)
    expect(r.deps.notify).toHaveBeenCalled()
    await r.service.stopManual()
  })

  it('斷線時 OBS 已停止且無路徑，重連後仍保留即時偵測，手動停止無檔收尾', async () => {
    const server = await fakeObs(); cleanup.push(server.close)
    const r = await rig(server)
    await r.service.startManual()
    server.setRecording(false)
    server.disconnect()
    await waitFor(() => r.service.status().detectionOnly === true)
    expect(r.service.status().phase).toBe('recording')
    await r.service.stopManual()
    expect(r.service.status().phase).toBe('idle')
  })

  it('僅偵測結束後改用內建，狀態不殘留 detectionOnly', async () => {
    const r = await rig(null, false)
    await r.service.startManual()
    await r.service.stopManual()
    r.deps.getSettings = () => ({ ...makeDeps(r.root).getSettings(), autoRecord: false })
    await r.service.startManual()
    expect(r.service.status()).toMatchObject({ backend: 'builtin', detectionOnly: false })
  })
})
